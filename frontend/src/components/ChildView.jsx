import React, { useState } from 'react';
import {
  Sparkles,
  Gamepad2,
  MessageCircle,
  Eye,
  ShieldAlert,
  ShieldCheck,
  Star,
  Award,
  Upload,
  RefreshCw,
  Heart,
  HelpCircle,
} from 'lucide-react';
import { runDeepfakeAnalysis } from '../utils/clientAnalyzers';

export default function ChildView() {
  const [activeTab, setActiveTab] = useState('checker'); // 'checker' | 'quiz'
  const [inputText, setInputText] = useState('');
  const [analyzing, setAnalyzing] = useState(false);
  const [result, setResult] = useState(null);
  const [quizScore, setQuizScore] = useState(0);
  const [quizAnswered, setQuizAnswered] = useState({});

  // Kid-specific threat checks (Zero banking, pure online safety)
  const KID_PRESETS = [
    {
      id: 'game_scam',
      title: '🎮 Free Robux / Game Coins Trick',
      icon: '🎮',
      text: 'FREE ROBUX & MINECRAFT COINS! Click http://free-robux-gemz.xyz and enter your gaming username & password now to unlock 10,000 gems!',
      type: 'game',
    },
    {
      id: 'stranger',
      title: '🕵️ Stranger Secret Message',
      icon: '🕵️',
      text: 'Hey friend, you play really well! What is your real name, address, and school name? Please don’t tell your parents, it is our secret!',
      type: 'stranger',
    },
    {
      id: 'bullying',
      title: '💬 Mean Chat / Cyberbullying',
      icon: '💬',
      text: 'You are so bad at this game! Nobody likes you, delete your account and leave our group right now, loser.',
      type: 'bullying',
    },
  ];

  // Kid safety analyzer rule-engine
  const analyzeKidText = (text) => {
    const lower = text.toLowerCase();
    let verdict = 'SAFE';
    let title = 'Looks Safe & Friendly!';
    let tip = 'This message seems okay. Keep being an awesome cyber friend!';
    let badge = '🛡️ Cyber Champ';

    if (
      lower.includes('robux') ||
      lower.includes('vbucks') ||
      lower.includes('free gems') ||
      lower.includes('free coins') ||
      lower.includes('password') ||
      lower.includes('unlock')
    ) {
      verdict = 'TRAP';
      title = '🚨 Free Game Coins Trick!';
      tip = 'Nobody gives away free game coins! They are trying to steal your game account or password. Never click links promising free game stuff.';
      badge = '🎮 Scam Spotter';
    } else if (
      lower.includes('secret') ||
      lower.includes('don’t tell') ||
      lower.includes('dont tell') ||
      lower.includes('your parents') ||
      lower.includes('address') ||
      lower.includes('school name') ||
      lower.includes('webcam')
    ) {
      verdict = 'DANGER';
      title = '🛑 Stranger Danger Alert!';
      tip = 'If someone online says "keep it a secret from your parents" or asks where you live or study, TELL A PARENT OR TEACHER IMMEDIATELY!';
      badge = '🕵️ Super Detective';
    } else if (
      lower.includes('loser') ||
      lower.includes('nobody likes you') ||
      lower.includes('hate you') ||
      lower.includes('ugly') ||
      lower.includes('stupid') ||
      lower.includes('bad at this')
    ) {
      verdict = 'MEAN';
      title = '💔 Mean Chat / Bullying Detected';
      tip = 'Words can hurt. Remember: it is NOT your fault. Block mean players, do not reply, and tell an adult you trust.';
      badge = '❤️ Kindness Hero';
    }

    return { verdict, title, tip, badge };
  };

  const handleCheck = () => {
    if (!inputText.trim()) return;
    setAnalyzing(true);
    setResult(null);

    setTimeout(() => {
      const res = analyzeKidText(inputText);
      setResult(res);
      setAnalyzing(false);
    }, 450);
  };

  const handleImageUpload = async (e) => {
    const file = e.target.files?.[0];
    if (!file) return;

    setAnalyzing(true);
    setResult(null);
    try {
      const deepfakeRes = await runDeepfakeAnalysis(file);
      const isFake = deepfakeRes.risk_level === 'HIGH_RISK';
      setResult({
        verdict: isFake ? 'TRAP' : 'SAFE',
        title: isFake ? '🤖 Computer-Made / AI Picture!' : '📸 Real Photo Detected!',
        tip: isFake
          ? 'This picture looks computer-generated by an AI robot. Don’t believe everything you see on the internet!'
          : 'This photo looks like a natural real camera photo.',
        badge: '🔍 Photo Detective',
      });
    } catch {
      // ignore
    } finally {
      setAnalyzing(false);
    }
  };

  // Fun Kid Quiz Questions
  const QUIZ = [
    {
      q: 'A pop-up in your online game says: "Enter your password to get 5,000 Free Gems!" What should you do?',
      options: ['Type my password quickly', 'Close it and tell my parent/guardian', 'Send it to my best friend'],
      correct: 1,
      why: 'Never share passwords! Free gem pop-ups are tricks to steal game accounts.',
    },
    {
      q: 'An online player asks: "Which school do you go to and what is your home address?"',
      options: ['Give my school name', 'Keep personal details private and never share', 'Ask them where they live first'],
      correct: 1,
      why: 'Always keep your real name, school, and home address secret from people on the internet.',
    },
    {
      q: 'Someone sends you a mean message in a gaming chat. What is the best superpower move?',
      options: ['Send a mean message back', 'Block & report them, then tell a grown-up', 'Cry alone'],
      correct: 1,
      why: 'Kindness and smart safety: block mean players and talk to someone you trust!',
    },
  ];

  const handleQuizChoice = (qIdx, optIdx) => {
    if (quizAnswered[qIdx] !== undefined) return;
    const isCorrect = optIdx === QUIZ[qIdx].correct;
    setQuizAnswered((prev) => ({ ...prev, [qIdx]: optIdx }));
    if (isCorrect) setQuizScore((prev) => prev + 1);
  };

  return (
    <div className="max-w-4xl mx-auto space-y-6 pb-12 animate-fade-in text-slate-900">
      {/* Friendly Hero Banner */}
      <div className="bg-gradient-to-r from-sky-400 via-indigo-400 to-purple-400 rounded-3xl p-6 sm:p-8 text-white shadow-xl relative overflow-hidden flex flex-wrap items-center justify-between gap-6">
        <div className="space-y-2 max-w-lg z-10">
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-white/20 backdrop-blur-md text-white font-extrabold text-sm">
            <Sparkles className="w-4 h-4 text-amber-300" />
            Shieldy&apos;s Kid Zone
          </div>
          <h1 className="text-3xl sm:text-4xl font-extrabold tracking-tight">
            Hi, Young Cyber Hero! 🛡️
          </h1>
          <p className="text-lg text-sky-100">
            Check game links, mean messages, or suspicious friend requests before trusting them.
          </p>
        </div>

        {/* Mascot / Badge */}
        <div className="flex items-center gap-3 bg-white/15 backdrop-blur-md px-5 py-4 rounded-3xl border border-white/30 z-10">
          <div className="text-4xl">🐶🛡️</div>
          <div>
            <div className="text-xs uppercase font-extrabold tracking-wider text-amber-200">Your Cyber Buddy</div>
            <div className="text-xl font-extrabold">Shieldy Guard</div>
          </div>
        </div>
      </div>

      {/* Mode Navigation: Scanner vs Quiz */}
      <div className="flex gap-3 bg-white p-2 rounded-2xl shadow-sm border border-slate-200 max-w-md mx-auto">
        <button
          onClick={() => setActiveTab('checker')}
          className={`flex-1 py-3 rounded-xl font-extrabold text-base transition flex items-center justify-center gap-2 ${
            activeTab === 'checker' ? 'bg-sky-500 text-white shadow-md' : 'text-slate-600 hover:text-black'
          }`}
        >
          <Gamepad2 className="w-5 h-5" />
          Safety Scanner
        </button>
        <button
          onClick={() => setActiveTab('quiz')}
          className={`flex-1 py-3 rounded-xl font-extrabold text-base transition flex items-center justify-center gap-2 ${
            activeTab === 'quiz' ? 'bg-purple-600 text-white shadow-md' : 'text-slate-600 hover:text-black'
          }`}
        >
          <Award className="w-5 h-5 text-amber-300" />
          Hero Quiz ({quizScore}/{QUIZ.length})
        </button>
      </div>

      {activeTab === 'checker' ? (
        <div className="space-y-6">
          {/* Input Box */}
          <div className="bg-white rounded-3xl p-6 sm:p-8 shadow-sm border-3 border-sky-200 space-y-4">
            <h2 className="text-2xl font-extrabold text-slate-900 flex items-center gap-2">
              <MessageCircle className="w-6 h-6 text-sky-600" />
              Paste any message, link, or drop a picture:
            </h2>

            <textarea
              value={inputText}
              onChange={(e) => setInputText(e.target.value)}
              rows={3}
              placeholder="Paste a message from Discord, Roblox, WhatsApp, or YouTube comments..."
              className="w-full text-lg p-4 rounded-2xl border-2 border-slate-300 focus:border-sky-500 focus:ring-2 focus:ring-sky-200 outline-none resize-none bg-sky-50/40 text-slate-900"
            />

            <div className="flex flex-wrap items-center justify-between gap-3 pt-2">
              <label className="cursor-pointer inline-flex items-center gap-2 px-5 py-3 rounded-2xl bg-slate-100 hover:bg-slate-200 border-2 border-slate-300 font-bold text-slate-800 transition">
                <Upload className="w-5 h-5 text-purple-600" />
                Drop Picture to Check if Fake
                <input type="file" accept="image/*" onChange={handleImageUpload} className="hidden" />
              </label>

              <button
                onClick={handleCheck}
                disabled={analyzing || !inputText.trim()}
                className="inline-flex items-center gap-2 px-7 py-3 rounded-2xl bg-sky-500 hover:bg-sky-600 disabled:opacity-50 text-white font-extrabold text-lg shadow-lg transition"
              >
                {analyzing ? <RefreshCw className="w-5 h-5 animate-spin" /> : <Sparkles className="w-5 h-5" />}
                Check Safety!
              </button>
            </div>
          </div>

          {/* Analysis Result */}
          {result && (
            <div
              className={`rounded-3xl p-6 sm:p-8 border-4 shadow-xl space-y-3 animate-fade-in-up ${
                result.verdict === 'SAFE'
                  ? 'bg-emerald-50 border-emerald-500 text-emerald-950'
                  : 'bg-rose-50 border-rose-500 text-rose-950'
              }`}
            >
              <div className="flex items-center gap-3">
                {result.verdict === 'SAFE' ? (
                  <ShieldCheck className="w-10 h-10 text-emerald-600 shrink-0" />
                ) : (
                  <ShieldAlert className="w-10 h-10 text-rose-600 shrink-0" />
                )}
                <div>
                  <span className="text-xs font-bold uppercase tracking-wider px-3 py-1 rounded-full bg-white border">
                    {result.badge}
                  </span>
                  <h3 className="text-2xl sm:text-3xl font-extrabold mt-1">{result.title}</h3>
                </div>
              </div>

              <p className="text-xl font-bold leading-relaxed">{result.tip}</p>

              {result.verdict !== 'SAFE' && (
                <div className="p-4 bg-white/90 rounded-2xl border border-rose-200 text-base font-semibold text-rose-900">
                  💡 <strong>Kid Safety Rule:</strong> Always ask a grown-up (Mom, Dad, or Teacher) before clicking surprising links or sending photos!
                </div>
              )}
            </div>
          )}

          {/* 1-Click Kid Stage Demos */}
          <div className="bg-white rounded-3xl p-6 shadow-sm border border-slate-200 space-y-3">
            <div className="text-sm font-extrabold uppercase tracking-wider text-slate-500">
              ⚡ Try 1-Click Kid Scenarios:
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
              {KID_PRESETS.map((p) => (
                <button
                  key={p.id}
                  onClick={() => {
                    setInputText(p.text);
                    setAnalyzing(true);
                    setResult(null);
                    setTimeout(() => {
                      setResult(analyzeKidText(p.text));
                      setAnalyzing(false);
                    }, 350);
                  }}
                  className="p-4 rounded-2xl border-2 border-slate-200 hover:border-sky-400 hover:bg-sky-50 text-left transition space-y-1"
                >
                  <div className="font-extrabold text-slate-900">{p.title}</div>
                  <div className="text-xs text-slate-500 line-clamp-2">{p.text}</div>
                </button>
              ))}
            </div>
          </div>
        </div>
      ) : (
        /* Fun Kid Cyber Quiz */
        <div className="space-y-4">
          {QUIZ.map((item, qIdx) => {
            const answered = quizAnswered[qIdx];
            return (
              <div key={qIdx} className="bg-white rounded-3xl p-6 shadow-sm border-2 border-purple-200 space-y-3">
                <div className="flex items-center gap-2 text-purple-700 font-extrabold text-sm">
                  <Star className="w-4 h-4 fill-amber-400 text-amber-400" />
                  Question {qIdx + 1} of {QUIZ.length}
                </div>
                <h3 className="text-xl font-extrabold text-slate-900">{item.q}</h3>

                <div className="space-y-2 pt-1">
                  {item.options.map((opt, optIdx) => {
                    const isSelected = answered === optIdx;
                    const isCorrect = optIdx === item.correct;
                    let btnStyle = 'bg-slate-50 hover:bg-purple-50 border-slate-200 text-slate-800';

                    if (answered !== undefined) {
                      if (isCorrect) {
                        btnStyle = 'bg-emerald-100 border-emerald-500 text-emerald-950 font-bold';
                      } else if (isSelected) {
                        btnStyle = 'bg-rose-100 border-rose-500 text-rose-950 font-bold';
                      }
                    }

                    return (
                      <button
                        key={optIdx}
                        disabled={answered !== undefined}
                        onClick={() => handleQuizChoice(qIdx, optIdx)}
                        className={`w-full text-left p-4 rounded-2xl border-2 text-base font-semibold transition ${btnStyle}`}
                      >
                        {opt}
                      </button>
                    );
                  })}
                </div>

                {answered !== undefined && (
                  <div className="p-3.5 rounded-2xl bg-purple-50 text-purple-950 font-semibold text-sm border border-purple-200">
                    💡 {item.why}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
